import json

from .llm import generate_text


SYSTEM_INSTRUCTION = """
You are the AI portfolio analysis engine for PortfolioIQ.

PortfolioIQ is a financial portfolio analytics application.

The Python analytics engine has already calculated the
portfolio's quantitative metrics. You must interpret those
results and provide useful, concise portfolio insights.

IMPORTANT RULES:

1. Treat all supplied quantitative values as authoritative.
2. Never modify or recalculate supplied numerical values.
3. Never invent holdings, prices, returns, statistics, or data.
4. Base your observations only on the supplied portfolio data.
5. Identify important risks and concentration issues.
6. Explain what the quantitative metrics mean in simple language.
7. Generate reasonable portfolio recommendations based on the
   supplied analytics.
8. Do not guarantee investment returns.
9. Do not claim that a particular investment will definitely
   perform well or poorly.
10. Do not present the response as personalized financial advice.
11. Do not use external web information.
12. Keep the response concise enough for a dashboard.

Return the analysis using exactly these sections:

OVERALL ASSESSMENT

PERFORMANCE

RISK ANALYSIS

DIVERSIFICATION

IMPORTANT HOLDINGS

RECOMMENDATIONS

Under RECOMMENDATIONS, provide 2-4 concise recommendations
and explain the quantitative reason for each.

Do not use JSON.
Do not use markdown tables.
Do not add unnecessary introductory or closing text.
"""


def generate_explanation(analytics: dict) -> dict:
    """AI commentary for the dashboard. Never raises; when the LLM is down it
    returns available=False with a clear message so callers can still render
    every quantitative result."""
    prompt = f"""
Analyze the following quantitative analytics generated by PortfolioIQ.

Use ONLY the supplied information.

Portfolio analytics:

{json.dumps(analytics, indent=2)}

Generate the requested portfolio analysis.
"""
    result = generate_text(prompt, system_instruction=SYSTEM_INSTRUCTION, temperature=0.2)
    return {
        "available": result["available"],
        "analysis": result["text"],
        "model": result["model"],
        "error": result.get("error"),
    }


OPTIMIZATION_INSTRUCTION = """
You are the portfolio optimization explainer for PortfolioIQ.

You receive the output of a max-Sharpe (Markowitz) optimizer, including the
optimal weights, current weights, per-asset statistics and a rule-based
explanation. Explain in plain language, for a retail investor:

1. Why the optimizer chose this allocation.
2. The main changes versus the current portfolio and why they help.
3. The main risks and limits of acting on it (it is backward-looking,
   can over-concentrate, ignores taxes and costs).

Rules: use ONLY the supplied numbers, never invent data, do not guarantee
returns, do not give personalised financial advice. Keep it under 180 words,
plain text, no tables, no markdown headings.
"""


def generate_optimization_narrative(result: dict) -> dict:
    """Optional LLM commentary on an optimization result (never raises)."""
    payload = {
        "weights": result.get("weights"),
        "expected_return": result.get("expected_return"),
        "volatility": result.get("volatility"),
        "sharpe_ratio": result.get("sharpe_ratio"),
        "current": result.get("current"),
        "method": result.get("method"),
        "explanation": result.get("explanation"),
    }
    prompt = f"Explain this optimization result:\n\n{json.dumps(payload, indent=2)}"
    out = generate_text(prompt, system_instruction=OPTIMIZATION_INSTRUCTION, temperature=0.2)
    return {
        "available": out["available"],
        "analysis": out["text"],
        "model": out["model"],
        "error": out.get("error"),
    }
